-- ── daily_words ─────────────────────────────────────────────
-- 하루 3개씩 카탈로그를 순서대로 소진한다. 단어 1430개 = 477일치.
--
-- 프로토타입 공식(일자 * 3 + slot)을 버린 이유: '일'(1~31)로만 인덱싱해서
-- 인덱스가 95 를 넘지 못한다. 단어가 12개일 땐 괜찮았지만 1430개에서는
-- 카탈로그의 93% 가 영영 나오지 않는다. src/lib/curriculum.ts 와 같은 규칙이다.
delete from public.daily_words;

insert into public.daily_words (learn_date, slot, word_id)
select
  date '2026-05-01' + n,   -- date + int = date (interval 캐스팅은 timestamp 가 된다)
  s.slot,
  o.id
from generate_series(0, 476) as n
cross join generate_series(0, 2) as s(slot)
join (
  select id, (row_number() over (order by sort_order) - 1)::int as idx, count(*) over () as total
  from public.words
) o on o.idx = ((n * 3) + s.slot) % o.total
on conflict (learn_date, slot) do update set word_id = excluded.word_id;

